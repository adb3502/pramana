"""Regenerate TABLE.md from current files. Usage: python scripts/table.py  (run from repo root)
Every column is recomputed from validation/, data/, ext/, verification/, parsed/. Prose above the table is kept."""
import json, glob, os, pathlib, datetime, zoneinfo

COLS = ["doc", "src", "candidates", "numbers", "span_copies", "data", "kappa", "role", "disputes", "triplets",
        "arith_fail", "external", "tc", "jev_agree_adj", "jev_usd", "adj_equiv_usd"]

def J(p):
    return json.load(open(p))

def row(d):
    v = J(f"validation/{d}.json")
    rows = [json.loads(l) for l in open(f"data/{d}.jsonl") if l.strip()]
    pp = pathlib.Path(f"parsed/{d}.json")
    src = J(pp).get("source_format", "jats") if pp.exists() else "jats"
    tcp = pathlib.Path(f"validation/{d}.typecheck.json")
    tc = J(tcp) if tcp.exists() else None
    tcs = f'{len(tc["A"])}/{len(tc["B"])}' if tc else "-"
    jp = pathlib.Path(f"verification/{d}.jev.json")
    jev_usd = (J(jp).get("report") or {}).get("cost_usd", 0) or 0 if jp.exists() else 0
    ap = pathlib.Path(f"ext/{d}.adj.json")
    adj = J(ap) if ap.exists() else {"decisions": []}
    final = {r["datum_id"]: r.get("role") for r in rows}
    disputed = {r["datum_id"] for r in rows if (r.get("needs_adjudication") or r.get("data_dispute")) and not r.get("span_copy")}
    dec = {x["datum_id"]: x for x in adj["decisions"] if x["datum_id"] in disputed and x.get("jev")}
    ok = sum(1 for k, x in dec.items() if x["jev"] == final[k])
    ext = v.get("external")
    return {"doc": d, "src": src, "candidates": v["candidates"], "numbers": v["numbers"], "span_copies": v.get("span_copies", 0),
            "data": sum(1 for r in rows if r.get("role")), "kappa": v["data_vs_not_kappa"], "role": v["role_agreement"],
            "disputes": len(disputed), "triplets": v["ratio_triplets"], "arith_fail": len(v["arithmetic_failures"]),
            "external": f'{ext["found"]}/{ext["total"]}' if ext else "-", "tc": tcs,
            "jev_agree_adj": f"{ok}/{len(dec)}" if dec else "-", "jev_usd": round(jev_usd, 4),
            "adj_equiv_usd": round(adj.get("cost_usd_equiv", 0) or 0, 4), "_tc": tc}

def main():
    docs = sorted(pathlib.Path(p).stem for p in glob.glob("validation/*.json")
                  if "." not in pathlib.Path(p).stem and os.path.exists(f"data/{pathlib.Path(p).stem}.jsonl"))
    R = [row(d) for d in docs]
    old = open("TABLE.md").read() if os.path.exists("TABLE.md") else ""
    header = []
    for l in old.splitlines():
        if l.startswith("|"): break
        header.append(l)
    header = "\n".join(header).rstrip()
    ssum = lambda c: sum(r[c] for r in R)
    tcA = sum(len(r["_tc"]["A"]) for r in R if r["_tc"]); tcB = sum(len(r["_tc"]["B"]) for r in R if r["_tc"])
    ev = [int(x) for r in R if r["external"] != "-" for x in r["external"].split("/")]
    ja = [r["jev_agree_adj"] for r in R if r["jev_agree_adj"] != "-"]
    tot = {"doc": f"TOTAL ({len(R)} docs)", "src": "-", "candidates": ssum("candidates"), "numbers": ssum("numbers"),
           "span_copies": ssum("span_copies"), "data": ssum("data"), "kappa": "-", "role": "-", "disputes": ssum("disputes"),
           "triplets": ssum("triplets"), "arith_fail": ssum("arith_fail"),
           "external": f"{sum(ev[0::2])}/{sum(ev[1::2])}" if ev else "-", "tc": f"{tcA}/{tcB}",
           "jev_agree_adj": f'{sum(int(x.split("/")[0]) for x in ja)}/{sum(int(x.split("/")[1]) for x in ja)}' if ja else "-",
           "jev_usd": round(ssum("jev_usd"), 4), "adj_equiv_usd": round(ssum("adj_equiv_usd"), 4)}
    lines = ["| " + " | ".join(COLS) + " |", "|" + "---|" * len(COLS)]
    for r in R + [tot]:
        lines.append("| " + " | ".join(str(r[c]) for c in COLS) + " |")
    now = datetime.datetime.now(zoneinfo.ZoneInfo("Asia/Kolkata")).strftime("%Y-%m-%d %H:%M IST")
    out = (header + "\n\n" if header else "") + "\n".join(lines) + f"\n\nGenerated by scripts/table.py at {now}\n"
    open("TABLE.md", "w").write(out)

if __name__ == "__main__":
    main()
